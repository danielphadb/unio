/**
 * Wortvorrat nach Namensstil (nameFinder-Chunk: `ar`, `pr`, `qu`, `Nu`, `gn`, `Tn`, `kr`,
 * `Vu`, `Ha`, `Mr`, `Ou`, `Iu`, `Ga`, `bn`, `wn`, `mn`, `zr`, `pn`, `Cr`, `$r`, `Fn`, `Pa`,
 * `Od`, `Fe`, `Br`, `Hr`, `Gn`).
 *
 * - Bausteine fuer Zusammensetzungen (Raum + werk = Raumwerk)
 * - lateinische und romanische Wurzeln fuer Kunstwoerter (terra, lumen ...)
 * - Bildwoerter (Lichte Hoehe), Saetze (Dach & Fach), echte Woerter (Raumplan),
 *   Fremdwoerter (Genius Loci) und alte Schreibweisen (Kontor zu Contor)
 */
import { LEXICON, type LexiconWord } from "./lexicon";
import { fold } from "./fold";
import { placeFieldOf, type PlaceField } from "./quality";
import type { NameFocus, StyleKey } from "../../types";

/** Stil- und Fokus-Merkmale eines Bausteins. */
export interface StyleTag {
  /** passende Stile, die ersten zwei zaehlen am meisten */
  s?: StyleKey[];
  /** passende Schwerpunkte */
  f?: NameFocus[];
  /** Grundqualitaet 0 bis 1 */
  q: number;
  /** nur bei passendem Stil oder Fokus */
  x?: boolean;
}

/** Baustein fuer Zusammensetzungen. */
export interface PartWord extends StyleTag {
  w: string;
}

/** Wort mit Begruendung. */
export interface StyleWord extends StyleTag {
  w: string;
  /** Begruendung fuer die Namenskarte */
  r: string;
  /** passt nur zu Lagen mit Grund (Land, Villen) */
  estate?: boolean;
  /** erst auf spaeteren Seiten */
  later?: boolean;
  /** nur fuer Wien */
  wien?: boolean;
}

/** Fremdwort mit Sprache und Bedeutung. */
export interface ForeignWord extends StyleTag {
  w: string;
  lang: string;
  m: string;
  estate?: boolean;
  later?: boolean;
  /** abgegriffen, seltener */
  worn?: boolean;
}

/** Wurzel fuer Kunstwoerter. */
export interface RootWord extends StyleTag {
  root: string;
  stem: string;
  /** Bedeutung, z. B. "terra (Erde, Grund)" */
  m: string;
  head?: string;
  tail?: string;
}

/** Kunstwort aus zwei Wurzeln. */
export interface RootBlend {
  w: string;
  a: string;
  b: string;
  q: number;
}

/** Fertiges Kunstwort aus einer Wurzel. */
export interface CoinedWord {
  w: string;
  root: string;
  m: string;
  q: number;
  later?: boolean;
}

/** Alte Schreibweise einer Endung. */
export interface OldSpelling {
  from: string;
  to: string;
  r: string;
  q: number;
}

