// Herkunft eines Worts

/** Herkunft eines bekannten Worts: deutsch, Redewendung, fremd, Kunstwort (`Fe`). */
export type WordOrigin = "de" | "phrase" | "fremd" | "kunst";

export const WORD_ORIGIN: ReadonlyMap<string, WordOrigin> = (() => {
  const map = new Map<string, WordOrigin>();
  for (const e of [...ECHTE_WOERTER, ...BILDWOERTER, ...BILDWORT]) map.set(fold(e.w), "de");
  for (const e of SAETZE) map.set(fold(e.w), "phrase");
  for (const e of FOREIGN) map.set(fold(e.w), "fremd");
  for (const e of COINED) map.set(fold(e.w), "kunst");
  for (const e of LEXICON)
    if (!map.has(fold(e.w))) map.set(fold(e.w), e.lang === "de" ? "de" : "fremd");
  return map;
})();

/** Lexikonwort nach gefaltetem Schluessel (`Br`). */
export const LEXICON_BY_KEY: ReadonlyMap<string, LexiconWord> = new Map(
  LEXICON.map((e) => [fold(e.w), e]),
);

/** Zusammensetzung aus Baustein und Grundwort, z. B. "Raumwerk" (`Hr`). */
export function isCompound(name: string): boolean {
  const low = name.toLocaleLowerCase("de-AT");
  return (
    !/\s/.test(name) &&
    COMPOUND_HEADS.some(
      (h) =>
        low.startsWith(h.w.toLocaleLowerCase("de-AT")) &&
        COMPOUND_TAILS.some((t) => low === h.w.toLocaleLowerCase("de-AT") + t.w),
    )
  );
}

/** Wortfeld eines Namens mit Angaben aus dem Lexikon (`Gn`). */
export function placeFieldOfName(name: string): PlaceField {
  const lex = LEXICON_BY_KEY.get(fold(name));
  return placeFieldOf(name, lex?.feld, lex?.m);
}
